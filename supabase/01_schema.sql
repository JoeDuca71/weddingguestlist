-- Wedding Guest List: tables, security and realtime.
-- Lives in the same Supabase project as the Wedding To-Do app and reuses its
-- allowlist (public.allowed_users, public.is_allowed, the sign-up block and
-- public.touch_updated_at). Run the to-do app's 01_schema.sql first (already done).
-- Run this once: SQL Editor > New query > paste > Run. Safe to run again.

-- One row per household / invitation. This is what the main list shows.
-- RSVP, rehearsal dinner, after-party and table fields are NOT stored here:
-- they live on each person and the app rolls them up ("Multiple" when people differ).
create table if not exists public.gl_families (
  id bigint generated by default as identity primary key,
  family_name text not null,              -- how we address them, e.g. "The Brad Johnson Family"
  affiliation text check (affiliation in ('Dylan Family', 'Dylan Friends', 'Joe Family', 'Joe Friends', 'Mutual')),
  invite_status text not null default 'Not Contacted'
    check (invite_status in ('Not Contacted', 'Texted for Address', 'Postcard Sent', 'Texted for RSVP', 'Done')),
  live_in_town text check (live_in_town in ('Yes', 'No')),
  hotel_status text not null default 'Unknown'
    check (hotel_status in ('Unknown', 'Maybe Host Hotel', 'Yes Host Hotel', 'Yes Tracey BnB', 'Yes Other Home', 'n/a')),
  hotel_swag text not null default 'Need to Do' check (hotel_swag in ('Need to Do', 'Done', 'Delivered', 'n/a')),
  transportation text not null default 'Unknown'
    check (transportation in ('Self', 'Hotel Shuttle', 'Tracey BnB Shuttle', 'Unknown')),
  address text,
  city text,
  state text,
  zip text,
  gift text,
  thank_you_sent text not null default 'No' check (thank_you_sent in ('Yes', 'No')),
  notes text,
  knot_ref text,                          -- matching key for future "Sync RSVPs from The Knot"
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- One row per guest, always inside a family.
create table if not exists public.gl_people (
  id bigint generated by default as identity primary key,
  family_id bigint not null references public.gl_families(id) on delete cascade,
  sort_order int not null default 0,
  first_name text,
  last_name text,
  role text not null default 'Guest',
  invited int not null default 1 check (invited >= 0),
  rsvp text not null default 'TBD' check (rsvp in ('TBD', 'Yes', 'No', 'Maybe')),
  rd_invited int not null default 0 check (rd_invited >= 0),
  rd_status text not null default 'TBD' check (rd_status in ('TBD', 'Yes', 'No', 'Maybe')),
  afterparty text not null default 'Unknown' check (afterparty in ('Unknown', 'Yes', 'No')),
  afterparty_swag text not null default 'Unknown' check (afterparty_swag in ('Unknown', 'Yes', 'No')),
  table_status text not null default 'Need to Seat' check (table_status in ('Need to Seat', 'Seated', 'n/a')),
  table_number text,
  phone text,
  email text,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists gl_people_family_idx on public.gl_people (family_id);

-- Shared column presets ("Attendee defaults", "Hotel Info defaults"), for later.
create table if not exists public.gl_views (
  id bigint generated by default as identity primary key,
  name text not null unique,
  columns jsonb not null default '[]',
  filters jsonb not null default '{}',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

drop trigger if exists gl_families_touch on public.gl_families;
create trigger gl_families_touch before update on public.gl_families
  for each row execute function public.touch_updated_at();
drop trigger if exists gl_people_touch on public.gl_people;
create trigger gl_people_touch before update on public.gl_people
  for each row execute function public.touch_updated_at();
drop trigger if exists gl_views_touch on public.gl_views;
create trigger gl_views_touch before update on public.gl_views
  for each row execute function public.touch_updated_at();

-- Only signed-in, allowed users (Joe and Dylan) can read or change anything.
alter table public.gl_families enable row level security;
alter table public.gl_people enable row level security;
alter table public.gl_views enable row level security;

drop policy if exists "allowed users" on public.gl_families;
create policy "allowed users" on public.gl_families
  for all to authenticated using (public.is_allowed()) with check (public.is_allowed());
drop policy if exists "allowed users" on public.gl_people;
create policy "allowed users" on public.gl_people
  for all to authenticated using (public.is_allowed()) with check (public.is_allowed());
drop policy if exists "allowed users" on public.gl_views;
create policy "allowed users" on public.gl_views
  for all to authenticated using (public.is_allowed()) with check (public.is_allowed());

