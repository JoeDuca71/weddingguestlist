-- Wedding Guest List: the B-list.
-- People we have NOT contacted yet and may or may not ever invite. If the main list
-- doesn't get enough RSVPs, we promote people from here (the app moves them onto the
-- main list and removes them from this table).
-- Run this once: SQL Editor > New query > paste > Run. Safe to run again.
-- Reuses the same allowlist and security rules as the rest of the guest list.

create table if not exists public.gl_blist (
  id bigint generated by default as identity primary key,
  priority int not null default 0,         -- 1 = first to invite; the app renumbers this with the up/down arrows
  family_name text not null,               -- how we'd address them, e.g. "The Brad Johnson Family"
  people text,                             -- one person per line, e.g. "Brad Johnson" (blank = one person from the name above)
  affiliation text check (affiliation in ('Dylan Family', 'Dylan Friends', 'Joe Family', 'Joe Friends', 'Mutual')),
  would_replace text,                      -- who they'd make room for, e.g. "a Dylan friend who declined"
  phone text,
  email text,
  city text,
  state text,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

drop trigger if exists gl_blist_touch on public.gl_blist;
create trigger gl_blist_touch before update on public.gl_blist
  for each row execute function public.touch_updated_at();

alter table public.gl_blist enable row level security;
drop policy if exists "allowed users" on public.gl_blist;
create policy "allowed users" on public.gl_blist
  for all to authenticated using (public.is_allowed()) with check (public.is_allowed());

do $$
begin
  alter publication supabase_realtime add table public.gl_blist;
exception when duplicate_object then null;
end $$;
